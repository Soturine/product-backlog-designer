"""Copy the skill assets (SKILL.md, procedures, entrypoints, top-level docs) into the package.

The packaged copy lets `pbd skill install` work from a wheel (no checkout). A test fails when the
copy drifts from the repository originals; run this tool after editing those files.

Usage: python tools/sync_skill_assets.py [--check]
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "src" / "pbd" / "skill_assets"
GROUPS = {".": ["SKILL.md"], "procedures": ["*.md"], "entrypoints": ["*.md"], "docs": ["*.md"]}


def expected() -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    for folder, patterns in GROUPS.items():
        base = ROOT / folder
        for pattern in patterns:
            for path in sorted(base.glob(pattern)):
                rel = path.relative_to(ROOT).as_posix()
                files[rel] = path.read_bytes()
    return files


def current() -> dict[str, bytes]:
    return {
        p.relative_to(DEST).as_posix(): p.read_bytes()
        for p in sorted(DEST.rglob("*"))
        if p.is_file() and p.name != "__init__.py" and "__pycache__" not in p.parts
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    want = expected()
    if args.check:
        have = current()
        drift = sorted(set(want) ^ set(have)) + sorted(k for k in want if k in have and want[k] != have[k])
        print("\n".join(drift) or "skill assets in sync")
        return 1 if drift else 0
    if DEST.exists():
        shutil.rmtree(DEST)
    for rel, data in want.items():
        target = DEST / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    (DEST / "__init__.py").write_text(
        '"""Packaged skill assets (generated by tools/sync_skill_assets.py)."""\n', encoding="utf-8"
    )
    print(f"synced {len(want)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
